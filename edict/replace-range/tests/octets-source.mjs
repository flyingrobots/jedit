// Generates the authored octet tables in src/rope/Octets.edict.
// Amblicit has no U8-to-U64 widening and no integer-to-byte conversion, so the
// persistent rope's canonical-CBOR codec reads and writes single octets
// through these total tables. A single 256-leaf comparison tree exceeds the
// provider host's response budget, so widening searches the high nibble and
// then the low nibble, 31 comparisons each.
const OCTET_COUNT = 256;
const NIBBLE = 16;
const HEX_WIDTH = 2;

function hexOctet(value) {
  return value.toString(NIBBLE).padStart(HEX_WIDTH, '0');
}

function searchTree(low, high, compare, leaf, indent) {
  if (high - low === 1) return leaf(low);
  const middle = low + (high - low) / 2;
  const inner = `${indent}  `;
  return `if ${compare(middle)}\n${inner}then ${searchTree(low, middle, compare, leaf, inner)}\n`
    + `${inner}else ${searchTree(middle, high, compare, leaf, inner)}`;
}

function rows(literals) {
  const lines = [];
  for (let index = 0; index < literals.length; index += NIBBLE) {
    lines.push(`    ${literals.slice(index, index + NIBBLE).join(', ')},`);
  }
  return lines.join('\n');
}

function table(literal) {
  return rows(Array.from({ length: OCTET_COUNT }, (_, value) => literal(value)));
}

export function octetsSource() {
  const high = searchTree(0, NIBBLE, (nibble) => `b < ${nibble * NIBBLE}u8`,
    (nibble) => `${nibble * NIBBLE}u64`, '  ');
  const low = searchTree(0, NIBBLE, (offset) => `below(b, base, ${offset}u64)`,
    (offset) => `${offset}u64`, '  ');
  return `// Generated by tests/octets-source.mjs; do not edit by hand.
package jedit.text.octets@1;

// The one-octet byte string whose value is v, or empty when v is not an octet.
fn octet(v: U64) -> Bytes<max=1> {
  let table: List<Bytes<max=1>, max=256> = [
${table((value) => `b"\\x${hexOctet(value)}"`)}
  ];
  return if v < listLen(table) then listAt(table, v) else b"";
}

// The octet whose value is v, or 255 when v is not an octet.
fn bound(v: U64) -> U8 {
  let table: List<U8, max=256> = [
${table((value) => `${value}u8`)}
  ];
  return if v < listLen(table) then listAt(table, v) else 255u8;
}

// Whether b is below the octet base + offset.
fn below(b: U8, base: U64, offset: U64) -> Bool {
  return base <= 240u64 && offset <= 15u64 && b < bound(base + offset);
}

// Sixteen times the high nibble of b.
fn highBase(b: U8) -> U64 {
  return ${high};
}

// The low nibble of b, given base = highBase(b).
fn lowOffset(b: U8, base: U64) -> U64 {
  return ${low};
}

// The value of one octet as a U64.
fn widen(b: U8) -> U64 {
  let base = highBase(b);
  let offset = lowOffset(b, base);
  return if base <= 240u64 && offset <= 15u64 then base + offset else 0u64;
}
`;
}
